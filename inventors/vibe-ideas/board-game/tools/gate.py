#!/usr/bin/env python3
"""gate.py — the deterministic acceptance gate (R3). No LLM anywhere in here.

    python3 board-game/tools/gate.py <project_dir> --bill <bill.json>

Runs the cadcode build itself, then answers one question with numbers: is this
a thing that can actually be printed, in the piece count the game's rules
require? Everything downstream (the review panel, the human gates) is opinion;
this file is the part that cannot be talked out of a verdict.

Checks, in order — the first hard failure still lets the rest run so a repair
round sees every problem at once, not one per cycle:

  1. build      `cadcode/scripts/cad` compiles the source and exports
                STEP/STL + one STL per named part. A non-`info` warning from
                the CAD kernel (disconnected_bodies, collision, sliver,
                invalid_brep) is blocking.
  2. bill       every component the rules call for exists as a named part in
                the declared quantity, and no part exists that the bill never
                asked for. Matching is by name prefix, so a bill line
                {"name": "tile", "qty": 48} wants tile_01..tile_48.
  3. pieces     each named part is ONE connected watertight body. Together
                with the bill check above, this is what replaces the old
                pipeline's fusion detector: 48 loose tiles arriving as one
                continuous mat now shows up as a bill mismatch (one part where
                48 were asked for), and a part that is secretly two lumps
                shows up here. Counting connected bodies on the ASSEMBLED mesh
                is not a fusion test any more — parts placed touching in
                display position legitimately share faces and merge.
  4. envelope   every part fits the printer, compared against sorted extents
                so a tall part may simply be laid down. Measured per part in
                its own frame, never the assembly's bounding box, which is a
                display arrangement and prints nothing.
  5. printability  overhang share and bridge span per part, taking the BEST of
                the six axis-aligned orientations. A lid modelled resting on
                its box reads as a 58mm unsupported bridge that disappears the
                moment you flip it to print, so measuring as-modelled would
                fail parts that are perfectly printable.
  6. interference  do any two PLACED pieces claim the same space? Everything
                above measures one part alone, and so is blind to the defect
                where two parts that were never booleaned together are simply
                drawn overlapping — nothing errors, because nothing was ever
                unioned. See interference.py for why this is measured as shared
                volume rather than distance or vertex containment.
                A part that MOVES is only as good as its worst position, and the
                pose it was exported in is not evidence about any of the others,
                so a project may declare its moving parts in `motion.json` and
                the check sweeps each one through its stated range. What that
                file declares is the axis and the range — design facts from the
                brief — never which position is the bad one; finding that is the
                job being automated.
  7. slice      OrcaSlicer, once per DISTINCT shape rather than per instance —
                48 identical tiles are one slice, not 48. When the slicer env
                vars are unset, or `--no-slice` is passed, nothing is measured
                and that lands in `unmeasured` below rather than passing quietly.
  8. fit_checks the project's own fit_checks.py, generated by the builder from
                the brief's `## Interfaces`. Whoever builds the geometry writes
                the check against the geometry they built, which is the whole
                reason the old part-name-prefix checker kept reporting real
                features as absent.
  9. lint       graduated lessons. A lesson that has cost two builds stops
                being advice and becomes a line in here.

Thresholds in this file are code-tier: improve.py may propose changes to them
only through a PR, never by editing at runtime. An agent that can lower its
own bar does not have a bar.

A check that could not reach a verdict lands in `unmeasured`, and a pass with
a non-empty `unmeasured` is not the same object as a clean pass. It does not
fail the gate: pieces resting in contact legitimately merge in the assembled
mesh, so failing on it would be a false alarm on correct designs and the gate
would be routed around within a week. It is carried instead — into gate.json,
into the printed line, into QUEUE.json on the next `advance`, and into a
refusal from `pipeline_queue.py ship` that only a human can accept with a
stated reason. Absence of screening is not safety: a gate that answers "fine"
when it did not look is worse than no gate, so the fix is to make the silence
visible rather than to guess a verdict.

Writes <project>/gate.json and prints one line. Exit 0 = PASS, 1 = FAIL.
"""
from __future__ import annotations

