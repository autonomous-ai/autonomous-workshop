import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
CADCODE = REPO_ROOT / "cadcode"
CAD_CLI = CADCODE / "scripts" / "cad"
VENV_PY = REPO_ROOT / ".venv" / "bin" / "python"

# interference.py is a sibling; gate.py is run by path from anywhere.
sys.path.insert(0, str(HERE))

# ---------------------------------------------------------------------------
# Thresholds — code tier. PR only.
# ---------------------------------------------------------------------------

# Bambu Lab P2S is 256x256x256mm nominal. The usable area is smaller than the
# advertised number (bed clips, exclusion zones near the edges), and a board
# game part parked at the very edge is exactly the part that fails at 3am on
# someone else's printer. The margin is the difference between "fits on paper"
# and "prints".
BED_X_MM = 256.0
BED_Y_MM = 256.0
BED_Z_MM = 256.0
BED_MARGIN_MM = 5.0

OVERHANG_FAIL_PCT = 50.0

# Local span, not area: a 16mm slot bridges fine, a 50mm unsupported ceiling
# sags. Measured as the inscribed-circle diameter of each down-facing patch.
BRIDGE_SPAN_MAX_MM = 25.0

# A connected body smaller than this is a tessellation artefact (a sliver
# triangle disconnected from its parent), not a game piece. Counting it as a
# component would turn a mesh defect into a phantom passing part.
MIN_BODY_VOLUME_MM3 = 20.0

CAD_WALL_CLOCK_S = 180.0

BLOCKING_SEVERITIES = ("warning", "error", "critical")


def usable_bed() -> tuple[float, float, float]:
    return (BED_X_MM - 2 * BED_MARGIN_MM,
            BED_Y_MM - 2 * BED_MARGIN_MM,
            BED_Z_MM - BED_MARGIN_MM)


# ---------------------------------------------------------------------------
# Source identity
# ---------------------------------------------------------------------------

def source_fingerprint(project: Path) -> str:
    """sha256 over the project's Python source, sorted by relative path.

    Borrowed from cadcode's own create-check: an unchanged source tree must
    never be silently re-verified as if something had been fixed. A repair
    round that reports success without changing a byte is a repair round that
    did nothing.
    """
    h = hashlib.sha256()
    files = [project] if project.is_file() else sorted(
        p for p in project.rglob("*.py")
        if ".input" not in p.parts and "__pycache__" not in p.parts)
    for p in files:
        h.update(str(p.relative_to(project if project.is_dir() else project.parent)).encode())
        h.update(p.read_bytes())
    return h.hexdigest()


# ---------------------------------------------------------------------------
# 1. Build
# ---------------------------------------------------------------------------

def run_cad(project: Path, out_dir: Path) -> dict:
    """Build + export through cadcode. Returns the CadcodeResult JSON."""
    python = str(VENV_PY) if VENV_PY.is_file() else sys.executable
    cmd = [python, str(CAD_CLI), str(project),
           "--out-dir", str(out_dir),
           "--wall-clock-s", str(CAD_WALL_CLOCK_S)]
    r = subprocess.run(cmd, capture_output=True, text=True,
                       timeout=CAD_WALL_CLOCK_S + 120)
    try:
        return json.loads(r.stdout.strip().splitlines()[-1])
    except (json.JSONDecodeError, IndexError):
        return {"ok": False, "error": {
            "code": "NO_JSON",
            "message": (r.stderr or r.stdout)[-500:] or "cad tool produced no output"}}


def blocking_warnings(cad: dict) -> list:
    return [f"{w.get('part', '?')}:{w.get('kind', '?')}: {w.get('detail', '')[:120]}"
            for w in (cad.get("warnings") or [])
            if str(w.get("severity", "info")).lower() in BLOCKING_SEVERITIES]


# ---------------------------------------------------------------------------
# 2. Bill of components
# ---------------------------------------------------------------------------

def load_bill(path: Path) -> list:
    """[{"name": "tile", "qty": 48}, ...] — the rules' own component list.

    Accepts either a bare list or an object with a `components` key, so the
    same file can be the idea spec or an extract from it.
    """
    raw = json.loads(path.read_text(encoding="utf-8"))
    items = raw.get("components", raw) if isinstance(raw, dict) else raw
    bill = []
    for item in items:
        name = str(item.get("name", "")).strip()
        qty = int(item.get("qty", item.get("quantity", 1)))
        if name and qty > 0:
            bill.append({"name": name, "qty": qty})
    return bill


def check_bill(bill: list, part_names: list) -> tuple[list, int]:
    """Match declared components against the parts the build actually named.

    Prefix matching, because a 48-tile bill line becomes tile_01..tile_48 in
    the assembly. Longest name first so a bill with both `tile` and
    `tile_corner` binds the specific one before the general one eats it.
    """
    total = sum(line["qty"] for line in bill)
    if not part_names:
        # cadcode collapses a single-child assembly into one unnamed model, so
        # "no named parts" means exactly one piece came out. For a one-piece
        # game that is correct and only the NAME is unverifiable; for anything
        # else it is the fusion signature — the pieces were unioned instead of
        # kept as separate named parts.
        if total == 1:
            return [], total
        return [f"bill: rules need {total} pieces across {len(bill)} kinds, but the "
                f"build exported one unnamed solid — the pieces were unioned "
                f"together instead of kept as separate named assembly children"], total

    findings = []
    unclaimed = set(part_names)
    for line in sorted(bill, key=lambda b: -len(b["name"])):
        name = line["name"]
        matched = {p for p in unclaimed
                   if p == name or p.startswith(name + "_") or p.startswith(name)}
        unclaimed -= matched
        if len(matched) != line["qty"]:
            findings.append(
                f"bill:{name}: rules need {line['qty']}, build named {len(matched)}")
    for extra in sorted(unclaimed):
        findings.append(f"bill:{extra}: part exists but no rule asks for it")
    return findings, total


# ---------------------------------------------------------------------------
# 3-5. Mesh measurement
# ---------------------------------------------------------------------------

def _bridge_span_mm(mesh) -> float:
    """Widest unsupported bridge, as inscribed-circle diameter of each
    down-facing patch. A 5mm-wide ring is a 5mm bridge no matter its diameter;
    a 50mm chamber roof is 50mm."""
    import networkx as nx
    import numpy as np

    nz = mesh.face_normals[:, 2]
    areas = mesh.area_faces
    down = np.where((nz < -0.95) &
                    (mesh.triangles_center[:, 2] > mesh.bounds[0][2] + 3.0))[0]
    if not len(down):
        return 0.0
    sel = set(down.tolist())
    g = nx.Graph((a, b) for a, b in mesh.face_adjacency if a in sel and b in sel)
    g.add_nodes_from(down.tolist())
    worst = 0.0
    for comp in nx.connected_components(g):
        comp = list(comp)
        if areas[comp].sum() < 200:  # trivial patch, not a bridge
            continue
        edges = np.sort(mesh.faces[comp][:, [0, 1, 1, 2, 2, 0]].reshape(-1, 2), axis=1)
        uniq, cnt = np.unique(edges, axis=0, return_counts=True)
        boundary = np.unique(uniq[cnt == 1])
        if not len(boundary):
            continue
        bpts = mesh.vertices[boundary][:, :2]
        cpts = mesh.triangles_center[comp][:, :2]
        d = np.sqrt(((cpts[:, None, :] - bpts[None, :, :]) ** 2).sum(-1)).min(1)
        worst = max(worst, float(2.0 * d.max()))
    return round(worst, 1)


# A part is printed in whatever orientation the owner drops it on the bed, not
# in the orientation the assembly displays it in — a lid modelled sitting on
# its box has its whole underside facing down and reads as a 58mm unsupported
# bridge, which vanishes the moment you flip it over to print. So the question
# the gate asks is the one a human asks in the slicer: is there ANY sane
# orientation in which this prints? Axis-aligned only; a part that needs an
# arbitrary tilt to print is a part the brief should have designed differently.
ORIENTATIONS = (("as-modelled", 0, 0), ("flip-X-180", 180, 0),
                ("X-90", 90, 0), ("X+90", -90, 0),
                ("Y-90", 0, 90), ("Y+90", 0, -90))


def _printability(mesh, rx: float, ry: float) -> tuple[float, float]:
    import numpy as np
    import trimesh

    m = mesh
    if rx or ry:
        m = mesh.copy()
        if rx:
            m.apply_transform(trimesh.transformations.rotation_matrix(
                np.radians(rx), [1, 0, 0]))
        if ry:
            m.apply_transform(trimesh.transformations.rotation_matrix(
                np.radians(ry), [0, 1, 0]))
    areas = m.area_faces
    nz = m.face_normals[:, 2]
    overhang = float(areas[nz < -0.7071].sum() / areas.sum() * 100.0) if areas.sum() else 0.0
    return round(overhang, 2), _bridge_span_mm(m)


def part_stats(stl: Path) -> dict:
    """Everything the gate needs to know about ONE named part.

    `bodies` is the fusion detector at the level that actually means something
    here: a named part is one manufactured piece, so a part whose mesh falls
    into several disconnected lumps cannot be printed as itself. Counting
    connected bodies on the ASSEMBLED mesh — which is what the old pipeline
    did, correctly, because the black box only ever returned one merged mesh —
    is meaningless now: parts placed touching each other in display position
    share coincident faces and merge, and the resulting open shells report
    nonsense volumes.
    """
    import trimesh

    m = trimesh.load(str(stl), force="mesh")
    split_error = None
    try:
        pieces = m.split(only_watertight=False)
    except Exception as exc:
        # Falling back to one piece is the safe assumption for everything else
        # in here, but it is also indistinguishable from a part that really is
        # one body — which would make this the quietest possible way to pass a
        # fused part. Say so instead; main() carries it into `unmeasured`.
        pieces = [m]
        split_error = f"{type(exc).__name__}: {exc}"
    bodies = max(1, len([p for p in pieces if abs(p.volume) >= MIN_BODY_VOLUME_MM3]))

    scored = []
    for label, rx, ry in ORIENTATIONS:
        overhang, bridge = _printability(m, rx, ry)
        # Prefer an orientation that clears both thresholds; among those (or
        # among all, when none clears) take the flattest bridge, then the
        # least overhang.
        passes = bridge <= BRIDGE_SPAN_MAX_MM and overhang <= OVERHANG_FAIL_PCT
        scored.append(((not passes, bridge, overhang), label, overhang, bridge))
    _, label, overhang, bridge = min(scored, key=lambda s: s[0])

    return {
        "watertight": bool(m.is_watertight),
        "bodies": bodies,
        "split_error": split_error,
        "volume_mm3": round(float(abs(m.volume)), 2),
        "bbox_mm": [round(float(x), 1) for x in (m.bounds[1] - m.bounds[0]).tolist()],
        "print_orientation": label,
        "overhang_pct": overhang,
        "bridge_span_mm": bridge,
    }


def fits_bed(bbox: list) -> bool:
    """A part may be laid down any way round on the bed, so compare sorted
    extents against the sorted usable envelope."""
    return all(part <= bed for part, bed
               in zip(sorted(bbox, reverse=True), sorted(usable_bed(), reverse=True)))


