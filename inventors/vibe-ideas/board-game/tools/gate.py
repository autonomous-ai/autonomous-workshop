def shape_key(stats: dict) -> str:
    """Identity of a SHAPE, so 48 identical tiles slice once."""
    return f"{stats['volume_mm3']}|{stats['bbox_mm']}"


def slice_stl(stl: Path) -> dict:
    """ORCA_PROFILE = "machine.json;process.json;filament.json" (full paths)."""
    cli = os.environ.get("ORCASLICER_CLI", "").strip()
    profile = os.environ.get("ORCA_PROFILE", "").strip()
    if not cli or not profile:
        return {"sliced": None}
    parts = [p.strip() for p in profile.split(";") if p.strip()]
    if len(parts) != 3:
        return {"sliced": False, "error": "ORCA_PROFILE needs machine;process;filament"}
    with tempfile.TemporaryDirectory() as td:
        cmd = [cli, "--load-settings", f"{parts[0]};{parts[1]}",
               "--load-filaments", parts[2],
               "--slice", "0", "--outputdir", td, str(stl)]
        try:
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
        except (OSError, subprocess.TimeoutExpired) as exc:
            return {"sliced": False, "error": str(exc)[:200]}
        gcodes = sorted(Path(td).glob("*.gcode"))
        if r.returncode != 0 or not gcodes:
            err = (r.stderr or r.stdout)[-200:]
            result_json = Path(td) / "result.json"
            if result_json.is_file():
                try:
                    err = json.loads(result_json.read_text()).get("error_string") or err
                except (OSError, ValueError):
                    pass
            return {"sliced": False, "error": err}
        head = gcodes[0].read_text(encoding="utf-8", errors="ignore")[:16000]
        out = {"sliced": True, "print_min": None, "filament_g": None}
        t = re.search(r"(?:estimated printing time.*?=|total estimated time:|"
                      r"model printing time:)\s*(?:(\d+)h)?\s*(?:(\d+)m)?", head, re.I)
        if t:
            out["print_min"] = int(t.group(1) or 0) * 60 + int(t.group(2) or 0)
        f = re.search(r"(?:filament used \[g\]\s*=|total filament weight \[g\]\s*:)"
                      r"\s*([\d.]+)", head, re.I)
        if f:
            out["filament_g"] = float(f.group(1))
        return out


# ---------------------------------------------------------------------------
# 7-8. Project's own checks, and graduated lessons
# ---------------------------------------------------------------------------

def load_brief(explicit: Path | None, home: Path) -> dict | None:
    """The brief for this project, if one can be found.

    A project lives at <slug>/project/ with its brief a level up at
    <slug>/brief.json, so that is the default; the project's own directory is
    searched first so a self-contained fixture needs no flag.
    """
    candidates = [explicit] if explicit else [home / "brief.json",
                                              home.parent / "brief.json"]
    for path in candidates:
        if path and path.is_file():
            try:
                return json.loads(path.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                return None
    return None


def run_fit_checks(project: Path) -> tuple[str | None, bool]:
    """The builder's own interface checks. Absent is a finding in its own
    right: a brief with an `## Interfaces` section and no fit_checks.py means
    nothing ever verified that the pieces fit the holes."""
    script = (project if project.is_dir() else project.parent) / "fit_checks.py"
    if not script.is_file():
        return None, True
    python = str(VENV_PY) if VENV_PY.is_file() else sys.executable
    r = subprocess.run([python, str(script)], capture_output=True, text=True,
                       timeout=300, cwd=script.parent)
    if r.returncode == 0:
        return "pass", True
    return (r.stdout + r.stderr)[-300:], False


# Each entry is a lesson that has already cost real builds. Prose in
# lessons.md is where a lesson starts; this list is where it ends up once it
# has repeated. improve.py may add rows here — through a PR.
#
# The first field is the rule's id, and it is load-bearing rather than
# decorative: lessons.md points at exactly this string, and
# graduation_check.py fails if it stops existing. Without an id a graduation
# could only claim "LINT_RULES exists", which stays true after the rule itself
# has been deleted. Never rename one without moving the marker with it.
LINT_RULES = [
    ("blanket-fillet",
     re.compile(r"\.edges\(\s*\)\s*\.(fillet|chamfer)\("),
     "blanket .edges().fillet/chamfer — OCCT synthesises a spherical vertex "
     "blend at every corner and tessellates it into phantom sliver bodies. "
     "Bake corner rounds into the 2D profile, or use directional selectors "
     "('|Z', '>Z')."),
]


def lint_source(project: Path) -> list:
    files = [project] if project.is_file() else [
        p for p in project.rglob("*.py") if "__pycache__" not in p.parts]
    issues = []
    for path in files:
        src = path.read_text(encoding="utf-8", errors="ignore")
        for rule_id, pattern, message in LINT_RULES:
            if pattern.search(src):
                issues.append(f"lint:{path.name}:{rule_id}: {message}")
    return issues


# ---------------------------------------------------------------------------
# Driver
# ---------------------------------------------------------------------------

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("project", type=Path, help="project dir or generator .py")
    ap.add_argument("--bill", type=Path,
                    help="component bill JSON; without it the piece-count "
                         "checks are reported but cannot fail the gate")
    ap.add_argument("--brief", type=Path,
                    help="brief.json; defaults to the project dir then its "
                         "parent. Read only to find parts declared to move.")
    ap.add_argument("--no-slice", action="store_true")
    ap.add_argument("--out", type=Path, help="default <project>/gate.json")
    args = ap.parse_args()

    project = args.project.resolve()
    home = project if project.is_dir() else project.parent
    out_path = args.out or (home / "gate.json")
    report: dict = {"project": str(project),
                    "source_sha256": source_fingerprint(project),
                    "bed_usable_mm": list(usable_bed())}
    fails: list = []
    # Everything a check wanted to look at and could not. Never merged into
    # `fails` — see the module docstring — and never dropped either.
    unmeasured: list = []

    # 1. build
    build_dir = home / "build"
    cad = run_cad(project, build_dir)
    report["build"] = {"ok": bool(cad.get("ok")),
                       "is_solid": cad.get("is_solid"),
                       "volume_mm3": cad.get("volume_mm3")}
    if not cad.get("ok"):
        err = cad.get("error") or {}
        report["build"]["error"] = f"{err.get('code', '?')}: {err.get('message', '')[:300]}"
        report["pass"] = False
        report["fails"] = [f"build_failed: {report['build']['error']}"]
        # Always present, so a reader never has to tell "measured nothing"
        # apart from "an older gate.json that had no such field".
        report["unmeasured"] = unmeasured
        out_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
        print("GATE FAIL " + json.dumps({"fails": report["fails"]}))
        return 1

    blocking = blocking_warnings(cad)
    fails += [f"cad:{w}" for w in blocking]
    report["build"]["blocking_warnings"] = blocking

    # 2. bill
    parts = cad.get("parts") or []
    part_names = [str(p.get("name", "")) for p in parts]
    report["part_count"] = len(parts) or 1
    expected_total = None
    if args.bill and args.bill.is_file():
        bill = load_bill(args.bill)
        bill_fails, expected_total = check_bill(bill, part_names)
        fails += bill_fails
        report["bill"] = {"expected_total": expected_total, "findings": bill_fails}

    # 3-5. per-part: one piece, closed, on the bed, printable in some orientation
    assembled = Path(cad["stl_path"])
    stls = [(str(p.get("name")), Path(p["stl_path"])) for p in parts if p.get("stl_path")]
    if not stls:
        stls = [("model", assembled)]
    seen: dict[str, str] = {}
    report["parts"] = {}
    for name, stl in stls:
        if not stl.is_file():
            fails.append(f"artifact:{name}: no STL exported")
            continue
        stats = part_stats(stl)
        report["parts"][name] = stats
        if stats.get("split_error"):
            unmeasured.append(f"pieces:{name}: the mesh could not be split into "
                              f"bodies ({stats['split_error']}), so it was counted "
                              f"as one — a fused part would look identical")
        if stats["bodies"] != 1:
            fails.append(f"pieces:{name}: one named part but {stats['bodies']} "
                         f"disconnected bodies — cannot be printed as one piece")
        if not stats["watertight"]:
            fails.append(f"watertight:{name}: mesh is not closed")
        if not fits_bed(stats["bbox_mm"]):
            bx, by, bz = stats["bbox_mm"]
            mx, my, mz = usable_bed()
            fails.append(f"envelope:{name}: {bx}x{by}x{bz}mm does not fit the usable "
                         f"bed {mx}x{my}x{mz}mm in any orientation — split it")
        if stats["overhang_pct"] > OVERHANG_FAIL_PCT:
            fails.append(f"overhang:{name}: {stats['overhang_pct']}% down-facing "
                         f"even in its best orientation ({stats['print_orientation']})")
        if stats["bridge_span_mm"] > BRIDGE_SPAN_MAX_MM:
            fails.append(f"bridge:{name}: {stats['bridge_span_mm']}mm unsupported span "
                         f"> {BRIDGE_SPAN_MAX_MM}mm even in its best orientation "
                         f"({stats['print_orientation']})")
        seen.setdefault(shape_key(stats), name)

    # 6. interference between placed pieces. Wrapped because this is the one
    # check that reads the assembled mesh rather than the per-part exports, and
    # a gate that cannot reach a verdict is worse than one that reports it could
    # not measure something.
    try:
        from interference import check_interference, load_motions, unswept_moving_parts

        motions = load_motions(home / "motion.json")
        interference = check_interference(
            assembled,
            dict(stls),
            expected_components=expected_total,
            motions=motions,
        )
        fails += interference["findings"]
        report["interference"] = interference
        unmeasured += [f"interference: {note}"
                       for note in interference.get("inconclusive") or []]

        # A part the brief says moves, that no motion sweeps, was passed on a
        # pose nothing ever questioned. Forgetting the declaration has to cost
        # what failing it costs, or saying nothing is the cheapest way through.
        brief = load_brief(args.brief, home)
        unswept = unswept_moving_parts(brief, motions)
        report["interference"]["unswept_moving_parts"] = unswept
        fails += [
            f"motion:{part}: the brief declares it turns or slides, but "
            f"motion.json does not sweep it — a pass here would be about a "
            f"motion nothing looked at"
            for part in unswept
        ]
    except Exception as exc:
        note = f"check did not run: {type(exc).__name__}: {exc}"
        report["interference"] = {"inconclusive": [note]}
        unmeasured.append(f"interference: {note}")

    # 7. slice, once per distinct shape
    report["distinct_shapes"] = len(seen)
    if not args.no_slice:
        sliced = {}
        by_name = dict(stls)
        for key, name in seen.items():
            result = slice_stl(by_name[name])
            sliced[name] = result
            if result.get("sliced") is False:
                fails.append(f"slice:{name}: {result.get('error', 'slicer failed')}")
        report["slice"] = sliced
        # One line for the whole run, not one per shape. The information is
        # identical either way and the twelve-line version is the kind of noise
        # that teaches an owner to skim past the section that matters.
        skipped = [name for name, r in sliced.items() if r.get("sliced") is None]
        if skipped:
            unmeasured.append(
                f"slice: no slicer configured (ORCASLICER_CLI / ORCA_PROFILE), so "
                f"none of the {len(skipped)} distinct shape(s) was put through it — "
                f"nothing here knows they slice, or how long they take to print")
    else:
        unmeasured.append("slice: --no-slice, so no shape was put through the "
                          "slicer and no print time is known")

    # 8. fit checks
    fit, fit_ok = run_fit_checks(home)
    report["fit_checks"] = fit if fit is not None else "absent"
    if not fit_ok:
        fails.append("fit_checks: failed")

    # 9. lint
    fails += lint_source(project)

    report["pass"] = not fails
    report["fails"] = fails
    # Not a fail, but never silent: a pass that could not measure something has
    # to say so, or "GATE PASS" means less than it looks like it means. This is
    # the field pipeline_queue.py reads on `advance` and refuses to `ship` on,
    # so it is a top-level key rather than something a reader has to go digging
    # for inside one check's sub-report.
    report["unmeasured"] = unmeasured
    out_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    summary = {"parts": report["part_count"],
               "expected": expected_total,
               "distinct_shapes": report["distinct_shapes"],
               "fails": fails}
    if unmeasured:
        summary["unmeasured"] = unmeasured
    print(("GATE PASS " if report["pass"] else "GATE FAIL ") + json.dumps(summary))
    return 0 if report["pass"] else 1


if __name__ == "__main__":
    sys.exit(main())
